function startUpstream(): Promise<Server> {
  return new Promise((resolve, reject) => {
    const server = createServer((request, response) => {
      // Drain the body: FerroGate sends a request body, and not reading it can
      // stall the socket.
      request.resume();
      request.on("end", () => {
        response.writeHead(200, { "content-type": "application/json" });
        response.end(JSON.stringify(UPSTREAM_COMPLETION));
      });
    });
    server.on("error", reject);
    server.listen(upstreamPort(), "127.0.0.1", () => resolve(server));
  });
}

async function waitForGateway(): Promise<void> {
  const deadline = Date.now() + 30_000;
  let lastError = "no attempt made";
  while (Date.now() < deadline) {
    if (gateway?.exitCode !== null && gateway?.exitCode !== undefined) {
      throw new Error(`ferrogate exited early with code ${gateway.exitCode}`);
    }
    try {
      const response = await fetch(`http://127.0.0.1:${gatewayPort()}/healthz`);
      if (response.ok) {
        return;
      }
      lastError = `HTTP ${response.status}`;
    } catch (error) {
      lastError = String(error);
    }
    await new Promise((resolve) => setTimeout(resolve, 200));
  }
  throw new Error(`ferrogate-poc harness: gateway did not become healthy in 30s (${lastError})`);
}

export async function setup(): Promise<void> {
  const binary = resolveFerroGateBinary();
  upstream = await startUpstream();

  workDir = mkdtempSync(path.join(tmpdir(), "ferrogate-poc-"));
  const configPath = path.join(workDir, "poc-harness.toml");
  writeFileSync(configPath, pocConfig());

  gateway = spawn(binary, ["run", "--config", configPath], {
    stdio: "ignore",
    env: { ...process.env, FERROGATE_POC_PROVIDER_KEY: "poc-upstream-key" },
  });
  gateway.on("error", (error) => {
    throw new Error(`ferrogate-poc harness: failed to spawn ${binary}: ${error}`);
  });

  await waitForGateway();
}

export async function teardown(): Promise<void> {
  gateway?.kill("SIGKILL");
  gateway = undefined;
  await new Promise<void>((resolve) => {
    if (!upstream) {
      resolve();
      return;
    }
    upstream.close(() => resolve());
  });
  upstream = undefined;
  if (workDir) {
    rmSync(workDir, { recursive: true, force: true });
    workDir = undefined;
  }
}
