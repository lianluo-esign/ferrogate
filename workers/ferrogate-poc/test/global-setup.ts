import { spawn, type ChildProcess } from "node:child_process";
import { createServer, type Server } from "node:http";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { POC_MODEL, POC_VIRTUAL_KEY, UPSTREAM_COMPLETION } from "./fixtures";
import { gatewayPort, REPO_ROOT, upstreamPort } from "./ports";

let gateway: ChildProcess | undefined;
let upstream: Server | undefined;
let workDir: string | undefined;

/**
 * Locate the `ferrogate` binary.
 *
 * Deliberately does NOT build it. `scripts/check-workers.sh` runs in a
 * Node/npm-only lane (see AGENTS.md "CI Workflow Structure" and
 * .github/workflows/workers.yml), so invoking cargo from here would break that
 * contract. Missing binary is therefore a hard, named failure rather than a
 * skip: an unproven PoC must not read as a passing one.
 */
function resolveFerroGateBinary(): string {
  const explicit = process.env.FERROGATE_BIN;
  const candidates = explicit
    ? [explicit]
    : [
        path.join(REPO_ROOT, "target", "debug", "ferrogate"),
        path.join(REPO_ROOT, "target", "release", "ferrogate"),
      ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  throw new Error(
    [
      "ferrogate-poc harness: no `ferrogate` binary found.",
      `  looked at: ${candidates.join(", ")}`,
      "  build one with `cargo build -p ferrogate-cli`, or set FERROGATE_BIN=<path>.",
      "  This suite proxies to the real binary on purpose -- without it there is no PoC,",
      "  only a Worker talking to a mock, so it fails instead of skipping.",
    ].join("\n"),
  );
}

